import AppKit
import UniformTypeIdentifiers

/// Polls the general pasteboard's change count. NSPasteboard has no change notification,
/// so a cheap timer with generous tolerance is the standard approach and lets the
/// system coalesce wake-ups on Apple silicon's efficiency cores.
final class ClipboardMonitor {
    private let onCapture: (ClipDraft) -> Void
    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    /// Hash of the text seen at the last change. Tcl/Tk apps like gitk change the text without
    /// bumping the change count, so every few polls the text itself is compared too.
    private var lastTextHash = ClipboardMonitor.textHash(NSPasteboard.general)
    private var pollsSinceTextCheck = 0
    private static let pollsPerTextCheck = 5
    /// Polls in a row that found a new change count on an empty pasteboard; ~6 s at most.
    private var emptyPolls = 0
    private static let maxEmptyPolls = 20

    /// Marker types that password managers and other apps use to ask clipboard
    /// managers not to record a copy (see nspasteboard.org). Always skipped.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    /// Marks a copy an app made by itself, like copy-on-select in a terminal. Skipped unless
    /// Settings → Privacy → Save Automatic Copies is on.
    private static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"

    /// Apps whose copies are never saved, from Settings → Privacy; Keychain Access and Passwords
    /// by default.
    private static var ignoredApps: Set<String> {
        Set(UserDefaults.standard.stringArray(forKey: Prefs.ignoredApps) ?? Prefs.defaultIgnoredApps)
    }

    private static let passwordsBundleID = "com.apple.Passwords"

    /// The page a Chromium browser (Chrome, Edge, Brave, Arc…) copied from.
    private static let chromiumSourceURLType = NSPasteboard.PasteboardType("org.chromium.source-url")

    /// Marks a copy that arrived from another device through Universal Clipboard.
    private static let remoteClipboardType = "com.apple.is-remote-clipboard"

    init(onCapture: @escaping (ClipDraft) -> Void) {
        self.onCapture = onCapture
    }

    func start() {
        let timer = Timer(timeInterval: 0.3, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.15
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Call after Klip writes to the pasteboard itself so the write isn't recorded again.
    func skipCurrentChange() {
        lastChangeCount = NSPasteboard.general.changeCount
        lastTextHash = Self.textHash(NSPasteboard.general)
        pollsSinceTextCheck = 0
    }

    /// Nil for no text, and for text too large to re-read every couple of seconds; Tk copies are small.
    private static func textHash(_ pasteboard: NSPasteboard) -> Int? {
        guard let text = pasteboard.string(forType: .string), text.utf8.count <= 256_000 else { return nil }
        return text.hashValue
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        if pasteboard.changeCount != lastChangeCount {
            // Screenshot tools clear the pasteboard, then write a big image a moment later under the
            // same change count. Seen empty, the change isn't handled yet: look again for a few seconds.
            if pasteboard.types?.isEmpty ?? true, emptyPolls < Self.maxEmptyPolls {
                emptyPolls += 1
                return
            }
            emptyPolls = 0
            lastChangeCount = pasteboard.changeCount
            lastTextHash = Self.textHash(pasteboard)
            pollsSinceTextCheck = 0
        } else {
            pollsSinceTextCheck += 1
            guard pollsSinceTextCheck >= Self.pollsPerTextCheck else { return }
            pollsSinceTextCheck = 0
            // Only a text-owning pasteboard can change silently; skip the read otherwise.
            guard lastTextHash != nil, pasteboard.types?.contains(.string) == true else { return }
            let hash = Self.textHash(pasteboard)
            guard hash != lastTextHash else { return }
            lastTextHash = hash
        }

        let types = pasteboard.types ?? []
        guard !types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }) else { return }
        guard UserDefaults.standard.bool(forKey: Prefs.saveAutomaticCopies)
              || !types.contains(where: { $0.rawValue == Self.autoGeneratedType }) else { return }

        // A Universal Clipboard copy came from the iPhone, not from the app that's in front here.
        let isRemote = types.contains { $0.rawValue == Self.remoteClipboardType }
        let app = isRemote ? nil : NSWorkspace.shared.frontmostApplication
        let bundleID = isRemote ? ClipDraft.iPhoneBundleID : app?.bundleIdentifier
        let appName = isRemote ? ClipDraft.iPhoneAppName : app?.localizedName
        let ignored = Self.ignoredApps
        // Ignoring Passwords also covers its menu bar popup, which leaves the current app in front.
        let ignoresPasswords = ignored.contains(Self.passwordsBundleID)
        guard !ignored.contains(bundleID ?? ""),
              !(ignoresPasswords && (bundleID == Self.passwordsBundleID + ".MenuBarExtra" || Self.isPasswordsPopupOpen())),
              !Self.isFromBrowserPasswordManager(pasteboard)
        else { return }

        let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
        if bundleID == Self.photosBundleID, let photo = Self.photoData(on: pasteboard, urls: urls) {
            // A photo copied in Photos is a file deep inside the Photos library; keep the picture itself.
            capture(imageData: photo, bundleID: bundleID, appName: appName)
        } else if !urls.isEmpty {
            onCapture(ClipDraft(kind: .file, filePaths: urls.map(\.path), sourceBundleID: bundleID, sourceAppName: appName))
        } else if let string = pasteboard.string(forType: .string),
                  !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard !(UserDefaults.standard.bool(forKey: Prefs.skipSecrets) && SecretDetector.containsSecret(string)) else { return }
            onCapture(.text(string, rtf: pasteboard.data(forType: .rtf), sourceBundleID: bundleID, sourceAppName: appName))
        } else if let raw = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) {
            capture(imageData: raw, bundleID: bundleID, appName: appName)
        }
    }

    private func capture(imageData: Data, bundleID: String?, appName: String?) {
        Task { [weak self] in
            let draft = await Task.detached(priority: .userInitiated) {
                ClipDraft.image(from: imageData, sourceBundleID: bundleID, sourceAppName: appName)
            }.value
            if let draft { self?.onCapture(draft) }
        }
    }

    /// Whether the Passwords menu bar popup is on screen. Copying from it leaves the current app
    /// in front and doesn't mark the copy, but the popup is still open when the copy lands.
    private static func isPasswordsPopupOpen() -> Bool {
        let pids = Set(NSRunningApplication.runningApplications(withBundleIdentifier: "com.apple.Passwords.MenuBarExtra")
            .map(\.processIdentifier))
        guard !pids.isEmpty,
              let windows = CGWindowListCopyWindowInfo([.optionOnScreenOnly, .excludeDesktopElements], kCGNullWindowID) as? [[String: Any]]
        else { return false }
        return windows.contains { window in
            pids.contains(window[kCGWindowOwnerPID as String] as? pid_t ?? -1)
                && (window[kCGWindowLayer as String] as? Int ?? 0) > 0
        }
    }

    /// A copy from a browser's own password manager page, such as chrome://password-manager or
    /// edge://wallet/passwords. Chrome also marks these concealed; this catches browsers that don't.
    private static func isFromBrowserPasswordManager(_ pasteboard: NSPasteboard) -> Bool {
        guard let source = pasteboard.string(forType: chromiumSourceURLType),
              let scheme = URL(string: source)?.scheme?.lowercased()
        else { return false }
        return !["http", "https", "file"].contains(scheme) && source.localizedCaseInsensitiveContains("password")
    }

    private static let photosBundleID = "com.apple.Photos"

    /// The image Photos put on the pasteboard, or else the single image file it pointed to.
    private static func photoData(on pasteboard: NSPasteboard, urls: [URL]) -> Data? {
        let imageTypes: [NSPasteboard.PasteboardType] = [.png, .init(UTType.jpeg.identifier), .init(UTType.heic.identifier), .tiff]
        if let data = imageTypes.lazy.compactMap({ pasteboard.data(forType: $0) }).first {
            return data
        }
        guard urls.count == 1, let type = UTType(filenameExtension: urls[0].pathExtension), type.conforms(to: .image) else {
            return nil
        }
        return try? Data(contentsOf: urls[0], options: .mappedIfSafe)
    }
}
